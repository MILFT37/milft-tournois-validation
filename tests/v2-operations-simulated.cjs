'use strict';
const assert=require('node:assert/strict');
const {init,grant,apply,enqueue,flush}=require('../v2/operations-core.cjs');
const c=(id,type,matchId,actorId,expectedVersion,extra={})=>({id,type,tournamentId:'tournoi-1',matchId,actorId,deviceId:'device-'+actorId,expectedVersion,...extra});
let base=init('tournoi-1','owner',['m1','m2'],['t1']);
base=grant(base,'owner','android','editor').state;
base=grant(base,'owner','pc','editor').state;
base=grant(base,'owner','guest','viewer').state;
assert.equal(grant(base,'guest','guest','admin').status,'forbidden');
const lease=c('e1','table.assign','m1','android',0,{tableId:'t1',expectedTableVersion:0});
const assigned=apply(base,'android',lease);assert.equal(assigned.status,'applied');
assert.equal(base.tables.t1.matchId,null,'Immutable base');
assert.equal(apply(assigned.state,'android',lease).status,'duplicate');
assert.equal(apply(assigned.state,'pc',lease).status,'forbidden','No forged actors');
const busy=c('e2','table.assign','m2','pc',0,{tableId:'t1',expectedTableVersion:0});
assert.equal(apply(assigned.state,'pc',busy).status,'conflict');
assert.equal(apply(assigned.state,'pc',{...busy,expectedTableVersion:1}).status,'table-busy');
const score=c('e3','set.record','m1','android',1,{setIndex:0,goals:{a:5,b:3}});
const saved=apply(assigned.state,'android',score);assert.equal(saved.status,'applied');
const pc=c('e4','set.record','m1','pc',1,{setIndex:0,goals:{a:5,b:4}});
const queue=JSON.parse(JSON.stringify(enqueue([],pc)));
const pending=flush(saved.state,'pc',queue);
assert.equal(pending.reports[0].status,'conflict');assert.equal(pending.pending.length,1);
assert.deepEqual(pending.state.matches.m1.sets[0],{a:5,b:3});
const done=apply(saved.state,'android',c('e5','match.validate','m1','android',2));
assert.equal(done.status,'applied');assert.equal(done.state.tables.t1.matchId,null);
const assigned2=apply(done.state,'pc',{...busy,id:'e6',expectedTableVersion:2});
assert.equal(assigned2.status,'applied');
const forfait=apply(assigned2.state,'pc',c('e7','match.forfeit','m2','pc',1,{winner:'b'}));
assert.equal(forfait.status,'applied');assert.deepEqual(forfait.state.matches.m2.forfeit.score,{a:3,b:5});
assert.equal(forfait.state.tables.t1.matchId,null);
assert.equal(apply(forfait.state,'pc',c('e8','match.reopen','m2','pc',2)).status,'applied');
assert.equal(apply(done.state,'android',c('e9','match.reopen','m1','android',3)).status,'applied');
assert.equal(apply(base,'guest',c('e10','set.record','m1','guest',0,{setIndex:0,goals:{a:1,b:2}})).status,'forbidden');
const other=init('tournoi-2','owner',['m1'],['t1']);
assert.equal(other.matches.m1.version,0);
console.log('OK V2 MAJ 68: atomic match/table commands, permissions, concurrency, idempotence, forfeit, reopen, tournament separation');
