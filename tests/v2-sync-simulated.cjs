'use strict';
const assert=require('node:assert/strict');
const {newWorkspace,grantRole,submit,enqueue,flush}=require('../v2/sync-core.cjs');
const origin=newWorkspace('club-tournoi-1','admin-1',['match-1','match-2']);
const members=grantRole(grantRole(origin,'android-operator','editor'),'pc-operator','editor');
const viewer=grantRole(members,'public-visitor','viewer');
assert.equal(origin.members['android-operator'],undefined,'Immutable role setup');
const scoreA={sets:[{home:5,away:3}],state:'playing'};
const scoreB={sets:[{home:5,away:4}],state:'playing'};
const a={id:'evt-a1',tournamentId:'club-tournoi-1',matchId:'match-1',actorId:'android-operator',deviceId:'samsung',expectedVersion:0,score:scoreA};
const b={id:'evt-b1',tournamentId:'club-tournoi-1',matchId:'match-1',actorId:'pc-operator',deviceId:'pc',expectedVersion:0,score:scoreB};
const queued=enqueue([],b);
assert.equal(JSON.parse(JSON.stringify(queued))[0].id,'evt-b1','Offline draft serializes to local storage');
const first=submit(viewer,a);
assert.equal(first.status,'applied');
assert.equal(first.workspace.matches['match-1'].version,1);
assert.equal(viewer.matches['match-1'].version,0,'Original workspace must remain untouched');
const second=flush(first.workspace,queued);
assert.equal(second.reports[0].status,'conflict','PC offline edit cannot overwrite Samsung result');
assert.equal(second.pending.length,1,'Conflicting offline edit must remain available for manual decision');
assert.deepEqual(second.workspace.matches['match-1'].score,scoreA,'Latest accepted result must survive conflict');
const repeated=submit(first.workspace,a);
assert.equal(repeated.status,'duplicate','Retrying same event is idempotent');
const collision=submit(first.workspace,{...a,score:scoreB});
assert.equal(collision.status,'id-collision','Reusing ID with different content is prohibited');
const withoutPermission=submit(viewer,{...a,id:'evt-view',actorId:'public-visitor'});
assert.equal(withoutPermission.status,'forbidden','Public viewer cannot change scores');
assert.equal(submit(viewer,{...a,id:'evt-wrong',tournamentId:'club-tournoi-2'}).status,'unknown-tournament');
assert.equal(submit(viewer,{...a,id:'evt-wrong-match',matchId:'match-3'}).status,'unknown-match');
const secondMatch=submit(first.workspace,{...b,id:'evt-b2',matchId:'match-2'});
assert.equal(secondMatch.status,'applied');
assert.equal(secondMatch.workspace.matches['match-1'].version,1,'Other match updates cannot modify match 1');
const repaired={...b,id:'evt-b3',expectedVersion:1};
const accepted=flush(first.workspace,enqueue([],repaired));
assert.equal(accepted.reports[0].status,'applied','Explicitly rebased edit accepted');
assert.equal(accepted.workspace.matches['match-1'].version,2);
assert.deepEqual(accepted.workspace.matches['match-1'].score,scoreB);
assert.equal(accepted.pending.length,0);
const distinct=newWorkspace('club-tournoi-2','admin-1',['match-1']);
assert.equal(distinct.matches['match-1'].version,0,'Different real tournaments remain independent');
assert.equal(flush(first.workspace,queued).reports[0].status,'conflict','Replay after reload still detects stale state');
console.log('OK V2 isolated: two devices, role security model, offline draft, conflict protection, idempotency, independent tournaments');
